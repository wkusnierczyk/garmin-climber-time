#!/usr/bin/env python3
"""Regenerate source/tests/ClimbGolden.mc from the browser simulator (#2).

The simulator (design/climber-time-simulator.html) is the behavioural reference, so the
watch's tests compare against values it computes, never against the watch's own output.
This loads a copy of the page with a probe appended inside its script, runs it in headless
Chrome, reads the probe's JSON back from the DOM and writes the Monkey C module.

    python3 tools/make-golden.py [CHROME]       (make golden)
"""
import html, json, os, re, subprocess, sys, tempfile

SIM = 'design/climber-time-simulator.html'
OUT = 'source/tests/ClimbGolden.mc'
CHROME = sys.argv[1] if len(sys.argv) > 1 else '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
BASE = 29462400                                  # an hour boundary, 2026
OFFSETS = [0, 1, 2, 3, 6, 9, 10, 12, 13, 14, 24, 28, 59, 60]   # every grade and proficiency, a round, an hour
TOP = 56                                         # the climb ends at :56 (DESIGN.md §11.3, §14.3)
TYPES = {'jug': 0, 'crimp': 1, 'sloper': 2, 'pinch': 3, 'edge': 4, 'micro': 5, 'foot': 6}   # Climb's enum
PROFS = {'beginner': 0, 'intermediate': 1, 'expert': 2}
WALLS = {'panel': 'Climb.LAYOUT_PANEL', 'half': 'Climb.LAYOUT_HALF', 'centre': 'Climb.LAYOUT_CENTRE'}

PROBE = """{const out={};const dev=DEVICES.r416;S.wallClip=DEF.wallClip;S.layout=DEF.layout;const G=geom(dev);const base=%d;
out.hash=[0,1,123456789,-5,base*31+7].map(n=>hash(n));
const m=mulberry32(hash(base*31+7));out.mul=[m(),m(),m()];
out.round=[0,1,2,3,491040*20,491040*20+19,491041*20].map(R=>roundIndex(R));
out.routes=%s.map(k=>{const am=base+k,R=getRoute(am,G,dev);const hs=[];for(let i=-4;i<=R.Lmax;i++){const h=R.holds[i];hs.push([h.x,h.y,h.type,h.s])}
  const P=attemptPlan(R,%d);
  return{k,grade:gradeFor(am),prof:profFor(am),color:colorFor(am).idx,M:R.M,Lmax:R.Lmax,dynos:[...R.dynos].sort((a,b)=>a-b),holds:hs,
    vols:(R.vols||[]).map(v=>[v.x,v.y,v.r]),plan:{falls:P.falls,misses:P.misses,endM:P.endM,segs:P.segs.map(s=>[s.t0,s.t1])}}});
out.wall=S.wallClip;out.linear=S.layout==='inline';
document.body.setAttribute('data-golden',JSON.stringify(out))}
requestAnimationFrame(frame);
})();"""

def probe():
    src = open(SIM).read()
    tail = 'requestAnimationFrame(frame);\n})();'
    if src.count(tail) != 1:
        sys.exit(f'{SIM}: the script no longer ends in {tail!r}; update the probe')
    page = src.replace(tail, PROBE % (BASE, json.dumps(OFFSETS), TOP))
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, 'probe.html')
        open(path, 'w').write(page)
        dom = subprocess.run([CHROME, '--headless=new', '--disable-gpu', f'--user-data-dir={tmp}/profile',
                              '--virtual-time-budget=5000', '--dump-dom', 'file://' + path],
                             capture_output=True, text=True, check=True).stdout
    m = re.search(r'data-golden="([^"]*)"', dom)
    if not m:
        sys.exit('the probe wrote nothing: open the simulator in a browser and look for a script error')
    return json.loads(html.unescape(m.group(1)))

def f(v):
    return f'{v:.4f}'

def write(j):
    L = ["""using Toybox.Test;

import Toybox.Lang;

// GENERATED by tools/make-golden.py (make golden) from design/climber-time-simulator.html,
// the behavioural reference: the watch has to reproduce its routes exactly (DESIGN.md §15.3,
// §17.2). 416 x 416 round screen, §14.3's defaults, minutes BASE + offset. LAYOUT and TIME_LINEAR
// are the simulator's defaults the values were made with; a test checks them against Draw's.
// Regenerate after any change to the route rules; never copy the watch's output in here.
(:test)
module ClimbGolden {

    const BASE = %d;
    const TOP = %d;
    const TOL = 0.05;               // px and moves; the watch computes in 32-bit floats
    const LAYOUT = %s;
    const TIME_LINEAR = %s;

    function geom() as Geom {
        return new Geom(416, 416, true, LAYOUT, TIME_LINEAR);
    }

    function near(a as Numeric, b as Numeric) as Boolean {
        return (a - b).abs() <= TOL;
    }
""" % (BASE, TOP, WALLS[j['wall']], 'true' if j['linear'] else 'false')]
    L.append('    const HASH_IN = [0l, 1l, 123456789l, -5l, %dl * 31 + 7] as Array<Long>;' % BASE)
    L.append('    const HASH_OUT = [%s] as Array<Long>;' % ', '.join(f'{v}l' for v in j['hash']))
    L.append('    const MUL = [%s] as Array<Float>;' % ', '.join(f'{v:.9f}' for v in j['mul']))
    L.append('    const ROUND_IN = [0, 1, 2, 3, 491040 * 20, 491040 * 20 + 19, 491041 * 20] as Array<Number>;')
    L.append('    const ROUND_OUT = [%s] as Array<Number>;' % ', '.join(map(str, j['round'])))
    L.append('    // Per route: offset, grade, proficiency (0 B, 1 I, 2 E), colour, moves, top level, jumps.')
    L.append('    const ROUTES = [\n' + ',\n'.join(
        f"        [{r['k']}, {r['grade']}, {PROFS[r['prof']]}, {r['color']}, {r['M']}, {r['Lmax']}, [{', '.join(map(str, r['dynos']))}] as Array<Number>]"
        for r in j['routes']) + '\n    ] as Array<Array>;')
    L.append('    // Per route: x, y, type (Climb enum) and size of each hold, k = -4 .. top level.')
    L.append('    const HOLDS = [\n' + ',\n'.join(
        '        [' + ', '.join(f'{f(x)}, {f(y)}, {TYPES[t]}, {f(s)}' for x, y, t, s in r['holds']) + '] as Array<Numeric>'
        for r in j['routes']) + '\n    ] as Array<Array<Numeric>>;')
    L.append('    // Per route: x, y and radius of each volume.')
    L.append('    const VOLS = [\n' + ',\n'.join(
        '        [' + ', '.join(f'{f(x)}, {f(y)}, {f(rr)}' for x, y, rr in r['vols']) + '] as Array<Float>'
        for r in j['routes']) + '\n    ] as Array<Array<Float>>;')
    L.append('    // Per route, the attempt plan to TOP: falls, missed jumps, end move, then segment t0, t1 pairs.')
    L.append('    const PLANS = [\n' + ',\n'.join(
        f"        [{r['plan']['falls']}, {r['plan']['misses']}, {f(r['plan']['endM'])}, [" +
        ', '.join(f'{f(a)}, {f(b)}' for a, b in r['plan']['segs']) + '] as Array<Float>] as Array'
        for r in j['routes']) + '\n    ] as Array<Array>;')
    L.append('}')
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print(f'{OUT}: {len(j["routes"])} routes from {SIM}')

write(probe())
